document.title = locale.value === 'en' ? messages.en['app.name'] : 'FMO仪表盘'

function interpolate(message, params) {
  return Object.entries(params || {}).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    message
  )
}

export function useLocale() {
  const isEnglish = computed(() => locale.value === 'en')

  function t(key, fallback = key, params) {
    const message = locale.value === 'en' ? messages.en[key] : fallback
    return interpolate(message || fallback, params)
  }

  function setLocale(value) {
    locale.value = value === 'en' ? 'en' : 'zh-CN'
    localStorage.setItem(STORAGE_KEY, locale.value)
    document.documentElement.lang = locale.value
    document.title = locale.value === 'en' ? messages.en['app.name'] : 'FMO仪表盘'
  }

  function toggleLocale() {
    setLocale(locale.value === 'en' ? 'zh-CN' : 'en')
  }

  return {
    locale,
    isEnglish,
    t,
    setLocale,
    toggleLocale
  }
}
